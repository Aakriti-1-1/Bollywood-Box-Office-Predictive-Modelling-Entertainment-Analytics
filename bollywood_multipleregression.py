from scipy import stats
from statsmodels.tsa.stattools import adfuller
from statsmodels.stats.diagnostic import acorr_ljungbox
from arch.unitroot import PhillipsPerron, DFGLS  # DFGLS = ERS test

# Select only numeric columns
numeric_cols = con.select_dtypes(include=[np.number]).columns


def full_summary_stats(df, columns, ljung_box_lag=10):

    results = []

    for col in columns:

        # Clean each series
        series = (
            pd.to_numeric(df[col], errors="coerce")
            .replace([np.inf, -np.inf], np.nan)
            .dropna()
        )

        # Skip series with insufficient observations
        if len(series) < 3:
            print(f"Skipping {col}: insufficient observations.")
            continue

        # Basic descriptive statistics
        mean = series.mean()
        median = series.median()
        std_dev = series.std()
        minimum = series.min()
        maximum = series.max()

        # Skewness and Pearson's kurtosis
        skewness = stats.skew(series)
        kurtosis = stats.kurtosis(series, fisher=False)

        # Jarque-Bera normality test
        jb_result = stats.jarque_bera(series)
        jb_stat = jb_result.statistic
        jb_pvalue = jb_result.pvalue

        # Initialize unit-root test results
        adf_stat = np.nan
        adf_pvalue = np.nan
        pp_stat = np.nan
        pp_pvalue = np.nan
        ers_stat = np.nan
        ers_pvalue = np.nan

        # Augmented Dickey-Fuller (ADF) test
        try:
            adf_result = adfuller(series, autolag="AIC")
            adf_stat = adf_result[0]
            adf_pvalue = adf_result[1]
        except (ValueError, np.linalg.LinAlgError) as e:
            print(f"ADF test failed for {col}: {e}")

        # Phillips-Perron (PP) test
        try:
            pp_test = PhillipsPerron(series)
            pp_stat = pp_test.stat
            pp_pvalue = pp_test.pvalue
        except (ValueError, np.linalg.LinAlgError) as e:
            print(f"PP test failed for {col}: {e}")

        # Elliott-Rothenberg-Stock (ERS / DF-GLS) test
        try:
            ers_test = DFGLS(series)
            ers_stat = ers_test.stat
            ers_pvalue = ers_test.pvalue
        except (ValueError, np.linalg.LinAlgError) as e:
            print(f"ERS test failed for {col}: {e}")

        # Ljung-Box test for serial autocorrelation
        lb_stat = np.nan
        lb_pvalue = np.nan

        if len(series) > ljung_box_lag:
            try:
                lb_result = acorr_ljungbox(
                    series,
                    lags=[ljung_box_lag],
                    return_df=True
                )

                lb_stat = lb_result["lb_stat"].iloc[0]
                lb_pvalue = lb_result["lb_pvalue"].iloc[0]

            except (ValueError, np.linalg.LinAlgError) as e:
                print(f"Ljung-Box test failed for {col}: {e}")

        # Store all results
        results.append({
            "Variable": col,
            "Observations": len(series),

            # Descriptive statistics
            "Mean": mean,
            "Median": median,
            "Std.Dev": std_dev,
            "Min": minimum,
            "Max": maximum,
            "Skewness": skewness,
            "Kurtosis": kurtosis,

            # Jarque-Bera test
            "Jarque-Bera": jb_stat,
            "JB p-value": jb_pvalue,

            # ADF test
            "ADF Stat": adf_stat,
            "ADF p-value": adf_pvalue,

            # Phillips-Perron test
            "PP Stat": pp_stat,
            "PP p-value": pp_pvalue,

            # ERS / DF-GLS test
            "ERS Stat": ers_stat,
            "ERS p-value": ers_pvalue,

            # Ljung-Box test
            f"Ljung-Box Q({ljung_box_lag})": lb_stat,
            f"Ljung-Box p-value ({ljung_box_lag})": lb_pvalue
        })

    return pd.DataFrame(results)


# Run the analysis
